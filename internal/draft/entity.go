// Package draft is the peticionamento Fatia 1 slice: creating and autosaving a
// peça (rascunho/draft). The advogado clicks "Peticionar" on an intimação (or
// opens a blank/processo draft), and this slice persists the initial context so
// the editor can open with pre-filled metadata and autosave.
//
// Scope: POST /v1/pecas (create), GET /v1/pecas/:id (read model), PATCH /v1/pecas/:id
// (autosave). Attachments (F2), AI review (F3), and signing/protocol (F4) are out of
// scope for this fatia.
//
// entity.go holds only the aggregate and its value types — it imports no repository,
// handler, or lib (the slice's inward dependency rule).
package draft

import "strings"

import "time"

// Draft is a peça (minuta) in its DRAFT lifecycle state. It is 1:1 with an intimação
// when source=intimation (enforced by the partial unique index); drafts from
// source=processo or source=blank have no intimação.
type Draft struct {
	ID           string
	TenantID     string
	CaseID       string // empty when source=blank and no case resolved yet
	IntimationID string // empty for blank/processo drafts
	PieceType    string
	Title        string
	Content      string // empty until autosave — plain text serialization (dual-write with StructuredContent)
	Status       string
	SagaState    string
	CreatedAt    time.Time
	UpdatedAt    time.Time
	// CreatedBy é o app_user.id do advogado que clicou "Redigir peça". Persistido
	// no INSERT (migration 0063) e usado pelo read model da lista pra mostrar
	// avatar/nome no card. Vazio pra peças criadas antes da migration.
	CreatedBy string

	// ── Costura Providência↔Tarefa↔Minuta (migration 0088) ────────────────────

	// TaskID is the task this draft was created FROM (task-sourced Create,
	// docs/erd-costura-providencia-tarefa-peca.md §2/§3). Empty for every
	// pre-existing path (source=intimation/processo/blank) — those never set it.
	TaskID string
	// PieceProfileKey is the structured catalog key (piece_profile.key) the
	// providência behind TaskID named — the draft INHERITS it, never re-chooses
	// (§3). Empty when the draft has no task_id, or when the providência's
	// piece_profile_key itself was empty (gera_peca=false, ciência).
	PieceProfileKey string

	// FilingNumber é o número/protocolo do tribunal (migration 0060), gravado
	// via MarkFiled quando o advogado marca a peça como protocolada. Vazio =
	// pré-protocolo OU protocolado sem número informado.
	FilingNumber string

	// SupersededAt (fatia 5, docs §7 questão 4 — "reclassificação depois de gerada a
	// peça"): quando a providência de origem é reclassificada DEPOIS de a peça já
	// existir, esta peça é marcada superseded (nunca editada/apagada — "descartar e
	// recomeçar", a decisão do Architect). nil para toda peça vigente (a esmagadora
	// maioria).
	SupersededAt *time.Time
	// SupersededByDraftID aponta a peça NOVA que substituiu esta. Vazio até o
	// backfill de Create (populateFromTask) rodar — há uma janela curta entre a
	// providência ser reclassificada e a peça nova existir, em que SupersededAt já
	// está setado mas SupersededByDraftID ainda não.
	SupersededByDraftID string

	// ── Generation params (Fatia 5 — teses/tom/instruções) ────────────────────
	// Chosen on POST /v1/pecas/:id/generate and persisted on the row (not on the
	// draft.generation_requested event) so the async worker rereads them here.

	// Tone is the closed-set writing register for Gerar. Defaults to
	// "tecnico" (the DB column default — identical wording to the
	// pre-Fatia-5 prompt).
	Tone string
	// Instructions is free-text advogado guidance for Gerar, capped at 2000
	// runes at the edge. Empty when the advogado provided none.
	Instructions string
	// SelectedTheses are the tese labels (plain strings, not structured
	// citations) the advogado picked from /theses to steer Gerar. Empty when
	// none were selected.
	SelectedTheses []string

	// ── Estrutura em blocos (Peça v2 — migration 0056) ────────────────────────
	// StructuredContent is the block-structured version of the draft (preamble +
	// sections). Nil for drafts that haven't been generated by the Fatia B
	// pipeline nor patched with structured content yet — the read model
	// parses Content on-the-fly and (best-effort) writes back.
	StructuredContent *StructuredContent
	// Authorship marks whether the peça is still under the assistant workflow
	// ("assistant" — Iterar tab shown) or the advogado has taken over and only
	// wants proactive review suggestions ("human_taken" — Revisão tab shown).
	// One-way today; flipping back is not modeled.
	Authorship string
}

// AuthorshipAssistant / AuthorshipHumanTaken are the closed-set values for
// Draft.Authorship (Peça v2). Match the CHECK constraint in migration 0056.
const (
	AuthorshipAssistant  = "assistant"
	AuthorshipHumanTaken = "human_taken"
)

// StructuredContent is the block-structured shape of a peça: a preamble
// (endereçamento + qualificação) followed by N sections identified by their
// Roman numeral. Persisted as jsonb (draft.structured_content) via the
// column added in migration 0056; the front-end consumes it directly to
// render section cards, chips, and per-section iteration/review targets.
//
// Kept as pointer on Draft so a nil value means "not populated yet" (falls
// back to parsing Content) vs "populated but empty" (a truly empty peça,
// which today isn't a real state).
type StructuredContent struct {
	Preamble StructuredPreamble  `json:"preamble"`
	Sections []StructuredSection `json:"sections"`
}

// StructuredPreamble is the pre-section block of the peça: the endereçamento,
// process reference line, and qualificação paragraphs — anything before the
// first Roman-numbered section heading.
type StructuredPreamble struct {
	Paragraphs []string `json:"paragraphs"`
}

// StructuredSection is one Roman-numbered section of the peça. ID is derived
// from the title (slug) — used by the FE chips and by the iterate endpoint's
// scope.section_id. ShortTitle is the title minus the leading article
// ("Dos fatos" → "Fatos") for chip display.
type StructuredSection struct {
	ID         string   `json:"id"`
	Roman      string   `json:"roman"`
	Title      string   `json:"title"`
	ShortTitle string   `json:"short_title"`
	Paragraphs []string `json:"paragraphs"`
}

// Providence is one task derived from the peça's intimation, surfaced in the
// FE sidebar (bulleted list "PROVIDÊNCIAS"). Empty for drafts without an
// intimation. Source is the closed set {AI, RULE, MANUAL} from the task table.
type Providence struct {
	ID     string `json:"id"`
	Title  string `json:"title"`
	Kind   string `json:"kind"`   // suggested action label ("peça", "juntada"…)
	Source string `json:"source"` // "AI" | "RULE" | "MANUAL"
	Status string `json:"status"` // "OPEN" | "DONE"
}

