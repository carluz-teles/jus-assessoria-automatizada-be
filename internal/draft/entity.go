// inferPieceType classifies the peça type when the client omits piece_type. It is
// the SINGLE source of truth for creation-time inference and is CONTENT-FIRST: the
// real signal lives in the teor da intimação (the DJEN type alone is ambiguous — the
// same "INTIMACAO" covers a defense, a manifestation, or a recursal window). It uses
// the type + class + subject + the HTML-stripped teor, is high-precision (conservative
// keyword match), and falls back to OTHER rather than mislabel. The generation LLM
// still adapts the actual peça to the teor; this drives the UI label and prompt hint.
//
// Precedence (most specific first):
//   - APPEAL  — a decision was rendered and a recursal window opened
//   - DEFENSE — cited to defend, or embargos/impugnação (execução/cumprimento)
//   - MOTION  — ordered to manifest/say/indicate (manifestação incidental)
//   - DEFENSE — fallback: an INTIMACAO with no content signal (historical default)
//   - OTHER   — no signal and not an INTIMACAO/CITACAO
//
// Note: the class "Execução" alone does NOT imply DEFENSE — the recipient may be the
// exequente ordered to indicate assets (→ MOTION). Only the content disambiguates.
func inferPieceType(it *IntimationContext) string {
	if it == nil {
		return PieceTypeOther
	}
	blob := strings.ToLower(strings.Join(
		[]string{it.Type, it.Class, it.Subject, stripHTML(it.Content)}, " "))

	switch {
	case containsAny(blob, "sentença", "acórdão", "recurso inominado", "prazo recursal",
		"para recorrer", "interpor recurso", "apelaç", "julgo procedente", "julgo improcedente"):
		return PieceTypeAppeal
	case it.Type == "CITACAO",
		containsAny(blob, "conteste", "contestação", "apresentar defesa", "oferecer defesa",
			"embargos à execução", "embargos do executado", "impugnação ao cumprimento"):
		return PieceTypeDefense
	case containsAny(blob, "manifeste-se", "manifestar-se", "manifestação", "diga sobre",
		"indique bens", "indicar bens", "requeira o que"):
		return PieceTypeMotion
	case it.Type == "INTIMACAO":
		// Fallback: an INTIMACAO with no recognized content signal defaults to DEFENSE
		// (the historical default) — better a sane hint than OTHER when the teor is
		// thin/empty (scraping gap). Content signals above still win (APPEAL/MOTION).
		return PieceTypeDefense
	default:
		return PieceTypeOther
	}
}

// containsAny reports whether s contains any of subs (all expected pre-lowercased).
func containsAny(s string, subs ...string) bool {
	for _, sub := range subs {
		if strings.Contains(s, sub) {
			return true
		}
	}
	return false
}

// pieceTypeByProfileKey is a LOCAL, hardcoded copy of the v1 piece_profile catalog
// (migration 0085, docs/erd-tipos-de-peca.md §6) mapping each known catalog key to
// the draft.piece_type (the closed set above) it corresponds to. Copied — not a
// query against piece_profile — for the same reason internal/actionitem/entity.go's
// knownPieceProfileKeys is local: this slice never imports actionitem/pieceprofile
// (slices never import another slice's domain), and the piece_profile FK is the
// real source of truth at insert time. Extend this map when the catalog grows
// (docs/erd-tipos-de-peca.md §6) — divergence here only falls back to
// inferPieceType, it never breaks the FK.
var pieceTypeByProfileKey = map[string]string{
	"peticao_inicial": PieceTypeComplaint,
	"contestacao":     PieceTypeDefense,
	"apelacao":        PieceTypeAppeal,
}

// pieceTypeFromProfileKey resolves the draft.piece_type the task-sourced Create
// flow should use for a given piece_profile_key — the providência's TYPE,
// INHERITED, never re-chosen (docs/erd-costura-providencia-tarefa-peca.md §3). ok
// is false when key is not in the local map (empty key — gera_peca=false — or a
// catalog key this slice doesn't know about yet); the caller falls back to
// inferPieceType in that case.
func pieceTypeFromProfileKey(key string) (pieceType string, ok bool) {
	pieceType, ok = pieceTypeByProfileKey[key]
	return pieceType, ok
}

// defaultProfileByPieceType is the reverse of pieceTypeByProfileKey: the catalog
// key a source=intimation draft should default to for a given draft.piece_type,
// used by Create's PART A fallback when the intimation has no peça-generating
// action_item that already chose a key. MOTION/OTHER map to no profile ("") —
// they fall back to the generic (non-profile) generation structure. Same local-
// copy rationale as pieceTypeByProfileKey (this slice never imports the catalog).
var defaultProfileByPieceType = map[string]string{
	PieceTypeDefense:   "contestacao",
	PieceTypeComplaint: "peticao_inicial",
	PieceTypeAppeal:    "apelacao",
}

// defaultProfileForPieceType resolves the catalog piece_profile_key a draft of the
// given piece_type defaults to when no action_item already picked one (PART A
// fallback). Returns "" for types with no catalog mapping (MOTION, OTHER, or any
// unknown value) — the draft then carries no profile and the generation renders the
// generic Fatos/Direito/Pedidos structure.
func defaultProfileForPieceType(pieceType string) string {
	return defaultProfileByPieceType[pieceType]
}

// ── Petition (Fatia 4 — peticionamento) ─────────────────────────────────────

// Petition is a signed, filed peça. It is immutable after creation. No tenant_id
// directly — isolation is via the draft FK (JOIN draft.tenant_id).
type Petition struct {
	ID             string
	DraftID        string
	CourtRecordID  string
	FiledAt        time.Time
	Receipt        map[string]any
	ObservedResult string // empty until observed
}

// ObservedResult closed set — the outcome the advogado records after the petition
// is filed.
const (
	ObservedResultOK          = "OK"
	ObservedResultAmendment   = "AMENDMENT"
	ObservedResultNotAdmitted = "NOT_ADMITTED"
	ObservedResultUntimely    = "UNTIMELY"
)

// validObservedResults is the lookup used by validation.
var validObservedResults = map[string]bool{
	ObservedResultOK:          true,
	ObservedResultAmendment:   true,
	ObservedResultNotAdmitted: true,
	ObservedResultUntimely:    true,
}

// ── Coverage summary (Fatia 4 — list read model) ────────────────────────────

// CoverageSummary is the trimmed review snapshot exposed in list endpoints.
// It comes from the most recent review for a draft.
type CoverageSummary struct {
	Grounded         bool `json:"grounded"`
	ChunksUsed       int  `json:"chunks_used"`
	SuggestionsTotal int  `json:"suggestions_total"`
}

// ── List read models (Fatia 4) ──────────────────────────────────────────────

// DraftListItem is one row in the paginated list of peças. It carries the
// fields the client needs for the list card — not the full aggregate.
type DraftListItem struct {
	ID              string
	PieceType       string
	Title           string
	Status          string
	SagaState       string
	CoverageSummary *CoverageSummary
	// Workflow timestamps — o FE deriva o step visível (Rascunho, Aguardando
	// assinatura, Aguardando protocolo, Protocolada) a partir do combo dos 3.
	SentToSigningAt *time.Time
	SignedAt        *time.Time
	FiledAt         *time.Time
	ObservedResult  *string
	CreatedAt       time.Time
	// Contexto do processo — pra mostrar CNJ no card sem 2ª chamada.
	CNJNumber string
	// Nome do autor da peça (join com app_user via created_by). Vazio pra
	// peças pré-migration 0063 ou quando o usuário foi removido do escritório.
	ResponsibleName string
	// Prazo da intimação de origem (join com deadline via notification_id) —
	// alimenta chips "Prazo em atraso"/"Prazo hoje" e o rótulo colorido no
	// card. Ambos nil quando não há deadline derivado.
	DeadlineEndDate  *time.Time
	DeadlineDaysLeft *int32
}

// DraftListResult is a page of peças plus whether a further page exists. Total
// is a separate COUNT(*) matching the exact same WHERE as the list query (no
// filtered-vs-tenant-wide distinction — single number, mirrors deadline's
// PrazosByProcessoResult).
type DraftListResult struct {
	Items   []DraftListItem
	HasMore bool
	Total   int64
}
